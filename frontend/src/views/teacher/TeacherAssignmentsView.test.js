// @vitest-environment jsdom
import { mount, flushPromises } from '@vue/test-utils'
import { beforeEach, expect, it, vi } from 'vitest'
import TeacherAssignmentsView from './TeacherAssignmentsView.vue'
import * as api from '../../api/teacher'
vi.mock('../../api/teacher', () => ({ createAssignment: vi.fn(), getAssignments: vi.fn(), getClasses: vi.fn(), getTopics: vi.fn(), getAssignment: vi.fn(), editAssignment: vi.fn(), deleteAssignment: vi.fn(), closeAssignment: vi.fn(), reopenAssignment: vi.fn() }))
beforeEach(() => {
  vi.resetAllMocks()
  window.scrollTo = vi.fn()
  window.confirm = vi.fn(() => true)
  api.getAssignments.mockResolvedValue([])
  api.getClasses.mockResolvedValue([{ id: 1, name: '一班' }, { id: 2, name: '二班' }])
  api.getTopics.mockResolvedValue([{ id: 9, code: 'DP', name: '动态规划' }])
  api.createAssignment.mockResolvedValue({ assignment_id: 7 })
})
it('已发布作业可关闭和删除，关闭后可恢复', async () => {
  api.getAssignments.mockResolvedValue([{ id: 7, title: '已发布作业', status: 'PUBLISHED', type: 'FINAL_PROJECT' }])
  const w = mount(TeacherAssignmentsView, { global: { stubs: { RouterLink: { template: '<a><slot /></a>' } } } }); await flushPromises()
  await w.findAll('button').find(b => b.text() === '关闭').trigger('click'); await flushPromises()
  expect(api.closeAssignment).toHaveBeenCalledWith(7)
  await w.findAll('button').find(b => b.text() === '删除').trigger('click'); await flushPromises()
  expect(api.deleteAssignment).toHaveBeenCalledWith(7)
  w.unmount()
})
async function openFinalForm() {
  const w = mount(TeacherAssignmentsView, { global: { stubs: { RouterLink: { template: '<a><slot /></a>' } } } })
  await flushPromises()
  await w.findAll('button').find(b => b.text() === '新建作业').trigger('click')
  await w.findAll('input').find(n => n.attributes('maxlength') === '200').setValue('期末演示')
  const dates = w.findAll('input[type="datetime-local"]')
  await dates[0].setValue('2029-12-01T12:00')
  await dates[1].setValue('2029-12-02T12:00')
  for (const checkbox of w.findAll('input[type="checkbox"]')) await checkbox.setValue(true)
  return w
}
it.each([[70, 30, .7, .3], [70.01, 29.99, .7001, .2999], [100, 0, 1, 0], [0, 100, 0, 1]])('新建默认60/40，修改%s/%s后保存实际配置', async (teacher, review, teacherWeight, reviewWeight) => {
  const w = await openFinalForm()
  expect(w.get('[aria-label="教师评分比例（%）"]').element.value).toBe('60')
  expect(w.get('[aria-label="同伴评审比例（%）"]').element.value).toBe('40')
  await w.get('[aria-label="教师评分比例（%）"]').setValue(teacher)
  await w.get('[aria-label="同伴评审比例（%）"]').setValue(review)
  await w.get('form').trigger('submit'); await flushPromises()
  expect(api.createAssignment).toHaveBeenCalledWith(expect.objectContaining({ teacher_weight: teacherWeight, designated_review_weight: reviewWeight }))
  w.unmount()
})
it.each([[70, 40], [-1, 101], [100, '']])('无效比例%s/%s阻止保存并在字段附近提示', async (teacher, review) => {
  const w = await openFinalForm()
  await w.get('[aria-label="教师评分比例（%）"]').setValue(teacher)
  await w.get('[aria-label="同伴评审比例（%）"]').setValue(review)
  await w.get('form').trigger('submit'); await flushPromises()
  expect(api.createAssignment).not.toHaveBeenCalled()
  expect(w.get('#grading-weight-error').text()).toBeTruthy()
  w.unmount()
})
it('编辑草稿保留已保存的自定义比例', async () => {
  api.getAssignments.mockResolvedValue([{ id: 7, title: '草稿', status: 'DRAFT', type: 'FINAL_PROJECT' }])
  api.getAssignment.mockResolvedValue({ title: '草稿', type: 'FINAL_PROJECT', updated_at: '2029-01-01T00:00:00Z', submit_deadline: '2029-12-01T04:00:00Z', review_deadline: '2029-12-02T04:00:00Z', classes: [{ id: 1 }, { id: 2 }], teacher_weight: '.725', designated_review_weight: '.275', rubric_items: [{ name: '原理', max_score: 100, sort_order: 1 }] })
  api.editAssignment.mockResolvedValue({})
  const w = mount(TeacherAssignmentsView, { global: { stubs: { RouterLink: { template: '<a><slot /></a>' } } } })
  await flushPromises()
  await w.findAll('button').find(b => b.text().includes('编辑')).trigger('click'); await flushPromises()
  expect(w.get('[aria-label="教师评分比例（%）"]').element.value).toBe('72.5')
  expect(w.get('[aria-label="同伴评审比例（%）"]').element.value).toBe('27.5')
  await w.get('form').trigger('submit'); await flushPromises()
  expect(api.editAssignment).toHaveBeenCalledWith(7, expect.objectContaining({ teacher_weight: .725, designated_review_weight: .275 }))
  w.unmount()
})
it.each(['ALGORITHM_ANALYSIS', 'PROOF', 'OPEN_ENDED'])('教师配置 %s 只需题面、班级和截止时间，无需评分量表', async (type) => {
  const w = mount(TeacherAssignmentsView, { global: { stubs: { RouterLink: { template: '<a><slot /></a>' } } } }); await flushPromises()
  await w.findAll('button').find(b => b.text() === '新建作业').trigger('click')
  await w.get('[aria-label="作业类型"]').setValue(type)
  await w.get('textarea').setValue('请分析并给出证明。')
  const textInput = w.findAll('input').find(n => n.attributes('maxlength') === '200')
  await textInput.setValue('在线主观题')
  for (const field of w.findAll('input[type="datetime-local"]')) await field.setValue('2029-12-01T12:00')
  for (const checkbox of w.findAll('input[type="checkbox"]')) await checkbox.setValue(true)
  await w.get('form').trigger('submit'); await flushPromises()
  expect(api.createAssignment).toHaveBeenCalledWith(expect.objectContaining({ type, statement: '请分析并给出证明。', topic_ids: [9], teacher_weight: 1, designated_review_weight: 0, review_deadline: null, rubric_items: [], programming_problem: null }))
  expect(w.text()).not.toContain('评分量表')
  expect(w.text()).not.toContain('评审截止时间')
  w.unmount()
})

it.each(['PROOF', 'OPEN_ENDED', 'ALGORITHM_ANALYSIS', 'PROGRAMMING'])('%s 可以选择三个班，并可切回期末作业的两个班限制', async (type) => {
  api.getClasses.mockResolvedValue([{ id: 1, name: '一班' }, { id: 2, name: '二班' }, { id: 3, name: '三班' }])
  const w = mount(TeacherAssignmentsView, { global: { stubs: { RouterLink: { template: '<a><slot /></a>' } } } })
  await flushPromises()
  await w.findAll('button').find(b => b.text() === '新建作业').trigger('click')
  await w.get('[aria-label="作业类型"]').setValue(type)
  const classes = () => w.get('fieldset[aria-label="适用班级"]').findAll('input')
  for (const field of classes()) {
    expect(field.element.disabled).toBe(false)
    await field.setValue(true)
  }
  expect(classes().filter(f => f.element.checked)).toHaveLength(3)
  await w.get('[aria-label="作业类型"]').setValue('FINAL_PROJECT')
  expect(classes().filter(f => f.element.checked)).toHaveLength(2)
  expect(classes()[2].element.disabled).toBe(true)
  w.unmount()
})
